export type AccountExportTable = keyof typeof accountExportColumns;

export function sanitizeAccountExportRows(
  table: AccountExportTable,
  rows: unknown,
) {
  if (!Array.isArray(rows)) return [];
  const allowed = new Set<string>(accountExportColumns[table]);
  return rows.map((row) => {
    if (!row || typeof row !== "object" || Array.isArray(row)) return {};
    return Object.fromEntries(
      Object.entries(row).filter(([key]) => allowed.has(key)),
    );
  });
}
